import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { chmod, lstat, mkdir, realpath } from "node:fs/promises";
import { tmpdir, userInfo } from "node:os";
import { isAbsolute, join, resolve } from "node:path";
import { promisify } from "node:util";
import type { CacheScope, PiboxConfig } from "./config.js";
import { cachePreset, resolvePresetEnvironment } from "./cache-presets.js";
import type { SandboxMount } from "./sandbox.js";

const execFileAsync = promisify(execFile);
const CACHE_DIRECTORY_MODE = 0o700;

interface ResolvedCache {
  name: string;
  scope: CacheScope;
  hostPath: string;
  guestPath: string;
  environment: Record<string, string>;
}

interface ResolvedCaches {
  caches: ResolvedCache[];
  mounts: SandboxMount[];
  environment: Record<string, string>;
}

export async function resolveCaches(
  config: PiboxConfig,
  worktreeRoot: string,
): Promise<ResolvedCaches> {
  const definitions = Object.values(config.caches).sort((left, right) =>
    left.name.localeCompare(right.name),
  );
  if (definitions.length === 0) {
    return {
      caches: [],
      mounts: [],
      environment: { ...config.pibox.env },
    };
  }

  const root = cacheRoot();
  await ensurePrivateDirectory(resolve(root, ".."));
  await ensurePrivateDirectory(root);
  const repositoryHash = definitions.some((cache) => cache.scope === "repository")
    ? await hashRepositoryIdentity(worktreeRoot, config.directory)
    : undefined;
  const guestPaths = new Map<string, string>();
  const environment = new Map<string, { cache: string; value: string }>();
  const caches: ResolvedCache[] = [];

  for (const definition of definitions) {
    const preset = cachePreset(definition.name);
    const guestPath = definition.mount ?? preset?.mount;
    if (!guestPath) {
      throw new Error(
        `Unknown cache \`${definition.name}\` must specify an absolute guest \`mount\``,
      );
    }
    const conflictingCache = guestPaths.get(guestPath);
    if (conflictingCache) {
      throw new Error(
        `Caches \`${conflictingCache}\` and \`${definition.name}\` both mount ${guestPath}`,
      );
    }
    guestPaths.set(guestPath, definition.name);

    const scopeDirectory =
      definition.scope === "user"
        ? join(root, "user")
        : join(root, "repository", requireRepositoryHash(repositoryHash));
    const hostPath = join(scopeDirectory, definition.name);
    await ensurePrivateDirectory(hostPath);

    const cacheEnvironment = preset
      ? resolvePresetEnvironment(preset, guestPath)
      : {};
    for (const [name, value] of Object.entries(cacheEnvironment)) {
      const existing = environment.get(name);
      if (existing) {
        throw new Error(
          `Cache environment variable ${name} is provided by both \`${existing.cache}\` and \`${definition.name}\``,
        );
      }
      if (Object.hasOwn(config.pibox.env, name)) {
        throw new Error(
          `\`pibox.env.${name}\` conflicts with the environment generated by cache \`${definition.name}\``,
        );
      }
      environment.set(name, { cache: definition.name, value });
    }

    caches.push({
      name: definition.name,
      scope: definition.scope,
      hostPath: await realpath(hostPath),
      guestPath,
      environment: cacheEnvironment,
    });
  }

  return {
    caches,
    mounts: caches.map((cache) => ({
      source: cache.hostPath,
      target: cache.guestPath,
    })),
    environment: {
      ...Object.fromEntries(
        [...environment].map(([name, definition]) => [name, definition.value]),
      ),
      ...config.pibox.env,
    },
  };
}

export function assertCacheEnvironmentIsNotReserved(
  environment: Readonly<Record<string, string>>,
  reserved: Iterable<string>,
): void {
  for (const name of reserved) {
    if (Object.hasOwn(environment, name)) {
      throw new Error(`Pibox environment variable ${name} is reserved`);
    }
  }
}

function cacheRoot(): string {
  const user = typeof process.getuid === "function"
    ? String(process.getuid())
    : sanitizePathComponent(userInfo().username);
  return join(tmpdir(), `pibox-${user}`, "caches");
}

async function hashRepositoryIdentity(
  worktreeRoot: string,
  fallbackDirectory: string,
): Promise<string> {
  let identity: string;
  try {
    const { stdout } = await execFileAsync(
      "git",
      ["-C", worktreeRoot, "rev-parse", "--git-common-dir"],
      { encoding: "utf8" },
    );
    const value = stdout.trim();
    if (!value) throw new Error("empty git common directory");
    const commonDirectory = isAbsolute(value)
      ? value
      : resolve(worktreeRoot, value);
    identity = await realpath(commonDirectory);
  } catch {
    identity = await realpath(fallbackDirectory);
  }
  return createHash("sha256").update(identity).digest("hex");
}

async function ensurePrivateDirectory(path: string): Promise<void> {
  await mkdir(path, { recursive: true, mode: CACHE_DIRECTORY_MODE });
  const metadata = await lstat(path);
  if (!metadata.isDirectory() || metadata.isSymbolicLink()) {
    throw new Error(`Pibox cache path ${path} is not a directory`);
  }
  if (typeof process.getuid === "function" && metadata.uid !== process.getuid()) {
    throw new Error(`Pibox cache path ${path} is owned by another user`);
  }
  await chmod(path, CACHE_DIRECTORY_MODE);
}

function requireRepositoryHash(value: string | undefined): string {
  if (!value) throw new Error("Repository cache identity was not resolved");
  return value;
}

function sanitizePathComponent(value: string): string {
  const sanitized = value.replace(/[^A-Za-z0-9._-]+/g, "-");
  return sanitized || "user";
}
